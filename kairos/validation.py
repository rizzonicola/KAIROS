"""Scenario definitions and log-based safety checks for KAIROS validation.

The scenario runner exercises the real pinned Stockfish 19 build. These checks
are behavioural and safety observations; they are not an Elo measurement.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date
import re
from typing import Sequence

MOVE = r"[a-h][1-8][a-h][1-8][qrbn]?"
BESTMOVE_RE = re.compile(rf"^bestmove ({MOVE})(?: ponder {MOVE})?$")
ACCEPTED_RE = re.compile(rf"accepted pick=({MOVE}) verified_loss=([\d.]+)%")
VERIFY_RE = re.compile(rf"verify candidate=({MOVE}) versus sf_best={MOVE} budget=([\d.]+)%")
POSTURE_RE = re.compile(r"posture=(\w+) conf=")


