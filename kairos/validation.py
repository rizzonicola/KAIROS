@dataclass(frozen=True)
class ScenarioResult:
    name: str
    posture: str
    bestmove: str
    pick: str
    reranked: bool
    verified: bool
    verified_loss_pct: float | None
    budget_pct: float | None
    note: str


def parse_chunk(name: str, chunk: str, bestmove_line: str) -> ScenarioResult:
    best = BESTMOVE_RE.match(bestmove_line.strip())
    bestmove = best.group(1) if best else ""
    accepted = ACCEPTED_RE.search(chunk)
    verify = VERIFY_RE.search(chunk)
    postures = POSTURE_RE.findall(chunk)
    if postures:
        posture = postures[-1]
    elif "mate score observed" in chunk:
        posture = "mate-guard"
    else:
        posture = "n/a"

    if "mate score observed" in chunk:
        note = "mate-guard"
    elif "distill conversion" in chunk:
        note = "distill-skip"
    elif accepted:
        note = "verified-rerank"
    elif "verification rejected" in chunk:
        note = "rejected-rerank"
    elif "cumulative budget" in chunk:
        note = "budget-guard"
    elif "no eligible rerank" in chunk:
        note = "stockfish-best"
    else:
        note = "passthrough-or-best"

    return ScenarioResult(
        name=name,
        posture=posture,
        bestmove=bestmove,
        pick=accepted.group(1) if accepted else "",
        reranked=accepted is not None,
        verified=verify is not None,
        verified_loss_pct=float(accepted.group(2)) if accepted else None,
        budget_pct=float(verify.group(2)) if verify else None,
        note=note,
    )


def safety_issues(result: ScenarioResult) -> list[str]:
    issues: list[str] = []
    if not result.bestmove:
        issues.append("missing or malformed bestmove")
    if result.reranked:
        if not result.verified:
            issues.append("reranked pick without verification")
        if result.bestmove != result.pick:
            issues.append("accepted pick does not match bestmove")
        if result.verified_loss_pct is not None and result.budget_pct is not None:
            if result.verified_loss_pct > result.budget_pct + 1e-6:
                issues.append("verified loss exceeds effective budget")
    if result.note == "mate-guard" and result.reranked:
        issues.append("rerank after mate score")
    if result.note == "distill-skip" and result.reranked:
        issues.append("rerank in Distill conversion")
    return issues


def results_markdown(results: Sequence[ScenarioResult], run_date: str | None = None) -> str:
    lines = [
        "# Scenario validation results",
        "",
        f"Run date: {run_date or date.today().isoformat()}",
        "",
        "Generated by `scripts/run_scenarios.py` against the pinned local",
        "Stockfish 19 build. These are safety and behaviour observations, not an",
        "Elo measurement.",
        "",
        "| Scenario | Posture | Bestmove | Rerank | Verification | Loss | Budget | Note |",
        "|---|---|---|---|---|---:|---:|---|",
    ]
    for result in results:
        loss = (
            f"{result.verified_loss_pct:.3f}%"
            if result.verified_loss_pct is not None
            else "-"
        )
        budget = f"{result.budget_pct:.3f}%" if result.budget_pct is not None else "-"
        lines.append(
            f"| {result.name} | {result.posture} | {result.bestmove} | "
            f"{'yes' if result.reranked else 'no'} | "
            f"{'yes' if result.verified else 'no'} | {loss} | {budget} | {result.note} |"
        )
    lines.append("")
    return "\n".join(lines)
