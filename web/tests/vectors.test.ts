import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import type { Features, PositionStats } from "../src/core";
import { fiftyMoveBlocked, isSaturated, repetitionBlocked, resultBand } from "../src/guards";
import {
  POSTURES,
  WEIGHTS,
  PostureController,
  dominant,
  evidenceFromStats,
  inferMix,
  planToken,
  positionClass,
  scoreTrend,
  updateFragility,
  varietyTemperature,
  type Evidence,
  type FeatureName,
  type FragilityClass,
  type Mix,
  type Posture,
} from "../src/postures";
import { probeFeatures, type ProbeRecord } from "../src/scoring";
import { parseInfo, supportedPersonalitySearch } from "../src/uci";

/**
 * Frozen parity vectors generated by the Python reference of KAIROS v0.2.1
 * (see tests/vectors/legacy-v0.2.1/README.md). They are no longer regenerated.
 */

interface BoardCase {
  fen: string;
  move: string;
  halfmoveReset: boolean;
}

interface PostureVectors {
  weights: Record<Posture, Record<FeatureName, number>>;
  planTokens: Record<Posture, string>;
  trend: { history: number[]; current: number; expected: number }[];
  evidence: {
    stats: PositionStats;
    expected: number;
    history: number[];
    forcingDensity: number;
    opponentFragility: number;
    result: Evidence;
  }[];
  inference: { evidence: Evidence; mix: Mix; dominant: Posture }[];
  classes: {
    stats: PositionStats;
    expected: number;
    forcingDensity: number;
    class: FragilityClass;
  }[];
  fragility: { previous: number; loss: number; expected: number }[];
  variety: { variety: number; posture: string; forced: boolean; temperature: number }[];
  controller: {
    name: string;
    initialMix: Mix | null;
    steps: { mix: Mix; evidence: Evidence; forced?: Posture }[];
    finalMix: Mix;
  }[];
}

function load<T>(name: string): T {
  const text = readFileSync(new URL(`./vectors/legacy-v0.2.1/${name}`, import.meta.url), "utf8");
  return JSON.parse(text) as T;
}

function expectClose(actual: number, expected: number, label = ""): void {
  expect(Math.abs(actual - expected), label).toBeLessThanOrEqual(1e-9);
}

/** The Python vectors key positions by `placement side castling ep`; only the piece placement is needed here. */
function placement(fen: string): string {
  return fen.split(" ")[0];
}

function pawnMoveOrCapture(fen: string, move: string): boolean {
  const board: string[] = [];
  for (const row of placement(fen).split("/")) {
    let line = "";
    for (const ch of row) {
      line += /\d/.test(ch) ? ".".repeat(Number(ch)) : ch;
    }
    board.push(line);
  }
  const at = (sq: string): string => board[8 - Number(sq[1])][sq.charCodeAt(0) - 97];
  return at(move.slice(0, 2)).toLowerCase() === "p" || at(move.slice(2, 4)) !== ".";
}

describe("frozen v0.2.1 parity vectors", () => {
  it("matches the weight table and plan tokens", () => {
    const vectors = load<PostureVectors>("postures.json");
    expect(WEIGHTS).toEqual(vectors.weights);
    for (const posture of POSTURES) {
      expect(planToken(posture)).toBe(vectors.planTokens[posture]);
    }
  });

  it("matches trend and evidence normalization", () => {
    const vectors = load<PostureVectors>("postures.json");
    for (const item of vectors.trend) {
      expectClose(scoreTrend(item.history, item.current), item.expected);
    }
    for (const item of vectors.evidence) {
      const actual = evidenceFromStats(
        item.stats,
        item.expected,
        item.history,
        item.forcingDensity,
        item.opponentFragility,
      );
      for (const key of Object.keys(item.result) as (keyof Evidence)[]) {
        expectClose(actual[key], item.result[key], key);
      }
    }
  });

  it("matches inference, classes, fragility and variety", () => {
    const vectors = load<PostureVectors>("postures.json");
    for (const item of vectors.inference) {
      const actual = inferMix(item.evidence);
      for (const posture of POSTURES) {
        expectClose(actual[posture], item.mix[posture], posture);
      }
      expect(dominant(actual)).toBe(item.dominant);
    }
    for (const item of vectors.classes) {
      expect(positionClass(item.stats, item.expected, item.forcingDensity)).toBe(item.class);
    }
    for (const item of vectors.fragility) {
      expectClose(updateFragility(item.previous, item.loss), item.expected);
    }
    for (const item of vectors.variety) {
      expectClose(varietyTemperature(item.variety, item.posture, item.forced), item.temperature);
    }
  });

  it("matches parseInfo vectors", () => {
    const { cases } = load<{
      cases: {
        line: string;
        candidate: {
          multipv: number;
          depth: number;
          move: string;
          scoreKind: string;
          scoreValue: number;
          wdl: [number, number, number];
          pv: string[];
        } | null;
      }[];
    }>("parse_info.json");
    for (const item of cases) {
      expect(parseInfo(item.line), item.line).toEqual(item.candidate);
    }
  });

  it("matches the guard vectors", () => {
    const vectors = load<{
      resultBand: { expected: number; band: number }[];
      saturation: { expected: number; saturated: boolean }[];
      repetition: {
        fen: string;
        move: string;
        counts: Record<string, number>;
        baselineExpected: number;
        blocked: boolean;
      }[];
      fiftyMove: { fen: string; move: string; baselineExpected: number; blocked: boolean }[];
      supported: {
        line: string;
        supported: boolean;
        kind: string;
        amount: number;
        reason: string;
      }[];
    }>("guards.json");
    const boards = load<{ cases: (BoardCase & { positionKey: string })[] }>("board.json").cases;
    for (const item of vectors.resultBand) {
      expect(resultBand(item.expected), String(item.expected)).toBe(item.band);
    }
    for (const item of vectors.saturation) {
      expect(isSaturated(item.expected), String(item.expected)).toBe(item.saturated);
    }
    // The v0.2.1 guards took a Board; they now take the counts the core provides.
    // The frozen cases are mapped onto the new signatures; illegal-move cases are core concerns.
    for (const item of vectors.repetition) {
      const board = boards.find((c) => c.fen === item.fen && c.move === item.move);
      if (!board) {
        continue;
      }
      const prior = item.counts[board.positionKey] ?? 0;
      expect(repetitionBlocked(prior, item.baselineExpected), `${item.fen} ${item.move}`).toBe(
        item.blocked,
      );
    }
    for (const item of vectors.fiftyMove) {
      const board = boards.find((c) => c.fen === item.fen && c.move === item.move);
      const halfmove = Number(item.fen.split(" ")[4]);
      const resets = board ? board.halfmoveReset : pawnMoveOrCapture(item.fen, item.move);
      if (item.move === "e2e5") {
        continue; // illegal in the fixture; legality belongs to the core
      }
      expect(
        fiftyMoveBlocked(halfmove, resets, item.baselineExpected),
        `${item.fen} ${item.move}`,
      ).toBe(item.blocked);
    }
    for (const item of vectors.supported) {
      expect(supportedPersonalitySearch(item.line), item.line).toEqual({
        supported: item.supported,
        kind: item.kind,
        amount: item.amount,
        reason: item.reason,
      });
    }
  });

  it("matches probe feature formulas", () => {
    const vectors = load<{
      cases: {
        move: string;
        probeResults: Record<string, ProbeRecord>;
        nullThreat: number | null;
        expected: Partial<Features>;
      }[];
    }>("probes.json");
    for (const item of vectors.cases) {
      const actual = probeFeatures(item.probeResults[item.move], item.nullThreat);
      expect(Object.keys(actual).sort(), item.move).toEqual(Object.keys(item.expected).sort());
      for (const key of Object.keys(item.expected) as (keyof Features)[]) {
        expectClose(Number(actual[key] ?? 0), Number(item.expected[key] ?? 0), `${item.move} ${key}`);
      }
    }
  });

  it("matches controller hysteresis", () => {
    const vectors = load<PostureVectors>("postures.json");
    for (const scenario of vectors.controller) {
      const controller = new PostureController();
      if (scenario.initialMix) {
        controller.mix = scenario.initialMix;
      }
      for (const step of scenario.steps) {
        controller.update(step.mix, step.evidence, step.forced ?? null);
      }
      for (const posture of POSTURES) {
        expectClose(controller.mix[posture], scenario.finalMix[posture], `${scenario.name} ${posture}`);
      }
    }
  });
});
